val keystoreTargetFile = file(System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks")

tasks.register("generateKeystore") {
  outputs.file(keystoreTargetFile)
  doLast {
    val keystoreFile = outputs.files.singleFile
    val sPassword = System.getenv("STORE_PASSWORD") ?: "android"
    val kAlias = "upload"
    val kPassword = System.getenv("KEY_PASSWORD") ?: "android"

    if (!keystoreFile.exists()) {
      try {
        val builder = ProcessBuilder(
          "keytool", "-genkeypair",
          "-alias", kAlias,
          "-keyalg", "RSA",
          "-keysize", "2048",
          "-validity", "10000",
          "-keystore", keystoreFile.absolutePath,
          "-storepass", sPassword,
          "-keypass", kPassword,
          "-dname", "CN=MTOS Browser, OU=MTOS, O=MTOS, L=City, S=State, C=US"
        )
        builder.inheritIO()
        val process = builder.start()
        process.waitFor()
        println("Generated keystore at ${keystoreFile.absolutePath}")
      } catch (e: Exception) {
        println("Failed to automatically generate keystore: ${e.message}")
      }
    }
  }
}

tasks.named("preBuild") {
  dependsOn("generateKeystore")
}

